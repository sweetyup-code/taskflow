import { describe, it, expect } from "vitest";
import "../../public/voice-smart.js";

const { toSmart } = window.TaskflowVoice;

describe("Преобразование голосовых команд", () => {
  it("удаляет команду добавления задачи", () => {
    expect(toSmart("добавь задачу купить молоко"))
      .toBe("Купить молоко");
  });

  it("распознаёт срочный приоритет", () => {
    expect(toSmart("сделать отчёт срочно"))
      .toBe("Сделать отчёт !срочно");
  });

  it("распознаёт относительную дату", () => {
    expect(toSmart("напомни мне задачу позвонить завтра"))
      .toBe("Позвонить @завтра");
  });

  it("преобразует дату с названием месяца", () => {
    expect(toSmart("купить подарок 15 ноября"))
      .toBe("Купить подарок @15.11");
  });
});